/*
 * Shared storage adapter for online records.
 *
 * Every record calls window.storage.get(key, shared) / .set(key, value, shared) /
 * .remove(key, shared) / .getByPrefix(prefix, shared) with this exact signature. Nothing in any
 * record file talks to a database directly -- they only ever go through window.storage -- so this
 * is the single place that decides where facility data actually lives.
 *
 * === WHERE DATA LIVES TODAY ===
 * Browser localStorage, per device. There is no backend connected yet, by design: the forms are
 * being built and reviewed first. Nothing here reaches the network.
 *
 * === HOW THE BACKEND GETS CONNECTED LATER =================================================
 * This file is the ONLY seam. When the application's own PostgreSQL API is ready (fed from
 * SYSPRO via Microsoft Dataverse on a scheduled sync -- the app never queries SYSPRO directly),
 * you do NOT edit this file and you do NOT touch any of the 144 record pages. You write one new
 * file that implements the four methods below and hands it to window.storage.useBackend():
 *
 *     // public/lib/api-backend.js  (does not exist yet)
 *     window.storage.useBackend({
 *       name: 'api',
 *       async get(key)            { ... return { value: '<string>' } or null; },
 *       async set(key, value)     { ... return true/false; },
 *       async remove(key)         { ... return true/false; },
 *       async getByPrefix(prefix) { ... return { '<key>': '<value string>', ... }; }
 *     });
 *
 * ...and add its <script> tag AFTER data-store.js on the pages that need it. Contract:
 *   - All four are async. `value` is always an opaque string (records JSON.stringify themselves).
 *   - get() resolves to { value } or null. Never throws -- errors are swallowed and logged here.
 *   - Keys are namespaced strings like 'document_revision:double-seam' or 'submissions:brine'.
 *   - getByPrefix() must be ONE round trip. Pages that read ~130 keys at once (the Master Record
 *     Index reads every document_revision:*) will stall if it loops get().
 *
 * ROUTING: the `shared` argument decides which side a key lives on, and that stays true after a
 * backend is connected:
 *   shared === false  ->  ALWAYS this device's localStorage. Per-device state, never syncs.
 *   shared !== false  ->  the active backend (localStorage today, the API later). Facility-wide
 *                         record data: submissions, specs, document revisions, batch links.
 * Every record already passes shared:true for its real data, so the day a backend is registered
 * that data starts going to it and per-device state correctly stays put.
 * ==========================================================================================
 */
(function () {
  const PREFIX = 'facility_records:';

  // ------------------------------------------------- localStorage (always available)
  // Used directly for shared:false keys, and as the default backend for shared data until a
  // real one is registered.
  const LocalBackend = {
    name: 'local',
    async get(key) {
      try {
        const raw = window.localStorage.getItem(PREFIX + key);
        return raw === null ? null : { value: raw };
      } catch (e) {
        console.error('storage get failed (local)', e);
        return null;
      }
    },
    async set(key, value) {
      try {
        window.localStorage.setItem(PREFIX + key, value);
        return true;
      } catch (e) {
        console.error('storage set failed (local)', e);
        return false;
      }
    },
    async remove(key) {
      try {
        window.localStorage.removeItem(PREFIX + key);
        return true;
      } catch (e) {
        return false;
      }
    },
    async getByPrefix(prefix) {
      const out = {};
      try {
        for (let i = 0; i < window.localStorage.length; i++) {
          const k = window.localStorage.key(i);
          if (k && k.startsWith(PREFIX + prefix)) {
            out[k.slice(PREFIX.length)] = window.localStorage.getItem(k);
          }
        }
      } catch (e) {
        console.error('storage getByPrefix failed (local)', e);
      }
      return out;
    }
  };

  // ------------------------------------------------------------------ active backend
  let backend = LocalBackend;

  // Register the real backend (see the block comment above). Call once, before records read.
  function useBackend(impl) {
    const missing = ['get', 'set', 'remove', 'getByPrefix']
      .filter(m => typeof (impl || {})[m] !== 'function');
    if (missing.length) {
      console.error('[data-store] backend rejected, missing method(s): ' + missing.join(', '));
      return false;
    }
    backend = impl;
    console.info('[data-store] backend in use: ' + (impl.name || 'custom'));
    return true;
  }

  // Which backend shared data is going to right now -- 'local' until one is registered.
  function backendName() {
    return backend.name || 'custom';
  }

  // ----------------------------------------------------------------- public API
  // Signatures are frozen: records depend on them and must never change when the backend does.
  async function get(key, shared) {
    return (shared === false ? LocalBackend : backend).get(key);
  }

  async function set(key, value, shared) {
    return (shared === false ? LocalBackend : backend).set(key, value);
  }

  async function remove(key, shared) {
    return (shared === false ? LocalBackend : backend).remove(key);
  }

  // Every key sharing a prefix, in ONE round trip: { key: value, ... }.
  async function getByPrefix(prefix, shared) {
    return (shared === false ? LocalBackend : backend).getByPrefix(prefix);
  }

  window.storage = { get, set, remove, getByPrefix, useBackend, backendName };
})();
