#!/usr/bin/env node
// Generates Prisma models for per-record submission tables from data/record-definitions.json.
// Output: prisma/submission-models.prisma (to be appended to schema.prisma before migration).
//
// Naming: record key 'dry-export-pack-front-page' → model Sub_dry_export_pack_front_page
//         (@@map("sub_dry_export_pack_front_page")).
// Roster → child table: Sub_dry_export_pack_front_page_Row, with a FK back to the parent.
//
// Every field becomes a nullable String column (the canonical storage type for all form data —
// the engine always reads/writes strings). Typed columns (Int, Float, DateTime) are NOT used:
// the overhead of type coercion + null-vs-empty handling across 1800 fields isn't worth it when
// every query that needs typed access already knows the field and can cast. The definition layer
// owns the type metadata; the submission table is a flat store.
//
// Every submission row also carries:
//   id         String @id          — the client-generated uid('sub') / uid('entry')
//   status     String?             — 'draft' | 'submitted'
//   source     String?             — 'manual' | 'derived' | 'csv'
//   submittedAt DateTime?
//   createdAt  DateTime
//   updatedAt  DateTime
//   rawJson    String?             — the full JSON blob during transition, so nothing is lost
//   inSpec     Boolean?            — monitoring-log's per-entry spec evaluation

import { readFileSync, writeFileSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, '..');

const { definitions } = JSON.parse(readFileSync(resolve(root, 'data/record-definitions.json'), 'utf8'));

function toModelName(recordKey) {
  return 'Sub_' + recordKey.replace(/-/g, '_');
}

function toColName(fieldKey) {
  // Prisma column names must be valid identifiers. Field keys are already camelCase from the
  // engine configs, but some might start with a digit or clash with reserved words.
  let col = fieldKey;
  if (/^\d/.test(col)) col = 'f_' + col;
  // Avoid Prisma reserved words
  if (['id', 'status', 'source', 'createdAt', 'updatedAt', 'submittedAt', 'rawJson', 'inSpec'].includes(col)) {
    col = 'val_' + col;
  }
  return col;
}

const lines = [];
lines.push('');
lines.push('// ============================================================================');
lines.push('// AUTO-GENERATED per-record submission tables.');
lines.push('// Generated by scripts/generate-submission-schema.mjs — do not edit by hand.');
lines.push('// ============================================================================');
lines.push('');

for (const def of definitions) {
  const model = toModelName(def.recordKey);
  const tableName = model.toLowerCase();

  // Separate roster fields from top-level fields
  const topFields = [];
  const rosterFields = [];
  for (const f of def.fields || []) {
    const sec = def.sections && def.sections[f.sectionIndex];
    if (sec && sec.kind === 'roster') {
      rosterFields.push(f);
    } else {
      topFields.push(f);
    }
  }

  const hasRoster = rosterFields.length > 0;

  // ---- Parent model ----
  lines.push(`model ${model} {`);
  lines.push('  id          String    @id');
  lines.push('  status      String?');
  lines.push('  source      String?');
  lines.push('  submittedAt DateTime?');
  lines.push('  createdAt   DateTime  @default(now())');
  lines.push('  updatedAt   DateTime  @updatedAt');
  lines.push('  rawJson     String?');
  lines.push('  inSpec      Boolean?');
  lines.push('');

  const seenCols = new Set(['id', 'status', 'source', 'submittedAt', 'createdAt', 'updatedAt', 'rawJson', 'inSpec']);
  for (const f of topFields) {
    const col = toColName(f.key);
    if (seenCols.has(col)) continue; // dedup
    seenCols.add(col);
    lines.push(`  ${col.padEnd(24)} String?`);
  }

  if (hasRoster) {
    lines.push('');
    lines.push(`  rows ${model}_Row[]`);
  }

  lines.push('');
  lines.push(`  @@map("${tableName}")`);
  lines.push('}');
  lines.push('');

  // ---- Child (roster) model ----
  if (hasRoster) {
    const childModel = `${model}_Row`;
    const childTable = `${tableName}_row`;

    lines.push(`model ${childModel} {`);
    lines.push('  id       Int     @id @default(autoincrement())');
    lines.push(`  parentId String`);
    lines.push(`  parent   ${model} @relation(fields: [parentId], references: [id], onDelete: Cascade)`);
    lines.push('  position Int     @default(0)');
    lines.push('');

    const childSeen = new Set(['id', 'parentId', 'position']);
    for (const f of rosterFields) {
      const col = toColName(f.key);
      if (childSeen.has(col)) continue;
      childSeen.add(col);
      lines.push(`  ${col.padEnd(24)} String?`);
    }

    lines.push('');
    lines.push(`  @@index([parentId])`);
    lines.push(`  @@map("${childTable}")`);
    lines.push('}');
    lines.push('');
  }
}

const outPath = resolve(root, 'prisma/submission-models.prisma');
writeFileSync(outPath, lines.join('\n'), 'utf8');

console.log(`Generated ${definitions.length} submission models → ${outPath}`);
console.log(`Append to prisma/schema.prisma, then run: npx prisma migrate dev --name submission_tables`);
