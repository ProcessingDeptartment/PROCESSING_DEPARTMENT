#!/usr/bin/env node
// Generates Prisma models for per-record submission tables from data/record-definitions.json.
// Output: prisma/submission-models.prisma (to be appended to schema.prisma before migration).
//
// Naming: record key 'dry-export-pack-front-page' → model Sub_dry_export_pack_front_page
//         (@@map("sub_dry_export_pack_front_page")).
// Roster → child table: Sub_dry_export_pack_front_page_Row, with a FK back to the parent.
//
// Each field's Prisma column type is derived from its declared `type` in record-definitions.json
// (RecordFieldDef.type) via FIELD_TYPE_TO_PRISMA below — not a flat String for every field.
// Identifier-like types (jobsearch, jobnumber, recordpick, batchseq) stay String? because they
// aren't really typed values (job/batch codes, record references). `month` and `time` are typed
// too: month -> DateTime? @db.Date (stored as the 1st of that month), time -> DateTime? @db.Time
// (a real time-of-day column, no date attached). See claude/erp-reconciliation-prep.md for the
// field-by-field reasoning this supersedes.
//
// Every submission row also carries:
//   id         String @id          — the client-generated uid('sub') / uid('entry')
//   status     String?             — 'draft' | 'submitted'
//   source     String?             — 'manual' | 'derived' | 'csv'
//   submittedAt DateTime?
//   createdAt  DateTime
//   updatedAt  DateTime
//   rawJson    String?             — the full JSON blob during transition, so nothing is lost
//   inSpec     Boolean?            — monitoring-log's per-entry spec evaluation
//
// Job-level copies (receiving date, farm, processing-for, intake weight autofilled read-only from
// REC 7.1.2) get NO column — they live once in sub_abalone_receiving / the job_info view. See
// src/job-snapshot.js.
//
// The record's job-number field is always the column "jobNo" (JOB_COL), even where the form's
// field key is jobNumber, so every table joins to job_info the same way.

import { readFileSync, writeFileSync } from 'fs';
import { createHash } from 'crypto';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';
import { createRequire } from 'module';

const { jobSnapshotKeys, jobFieldKey, JOB_COL } = createRequire(import.meta.url)('../src/job-snapshot.js');

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, '..');

const { definitions } = JSON.parse(readFileSync(resolve(root, 'data/record-definitions.json'), 'utf8'));

const FIELD_TYPE_TO_PRISMA = {
  text: 'String?',
  number: 'Float?',
  yesno: 'Boolean?',
  date: 'DateTime? @db.Date',
  select: 'String?',
  textarea: 'String?',
  jobsearch: 'String?',
  month: 'DateTime? @db.Date', // <input type="month"> value ("2026-09") stored as its first day
  recordpick: 'String?',
  timestamp: 'DateTime?',
  digits: 'Int?',
  time: 'DateTime? @db.Time', // "HH:MM" stored as a time-of-day column (no date component)
  jobnumber: 'String?',
  batchseq: 'String?',
};

function prismaTypeFor(field, def) {
  if (field.type === 'computed' || field.type === 'derived') {
    // Both kinds are numeric in every current definition (see build-spec audit); fall back to
    // Float? for any future non-numeric computeFn rather than guessing further.
    return 'Float?';
  }
  return FIELD_TYPE_TO_PRISMA[field.type] || 'String?';
}

// Indexes: only the columns a lookup actually filters on -- each top-level link field (job number,
// ingredient/batch codes; RecordFieldDef.linkField). The store rewrites a record's whole table on
// every save, so every extra index costs a write; dates and status are deliberately not indexed
// (cross-record date queries go through the already-indexed SubmissionDateField).
// Names are explicit so the Prisma schema and the migration SQL cannot disagree; Postgres cuts
// identifiers at 63 bytes, so a long table+column name is shortened with a stable hash.
function indexName(table, col) {
  const full = `${table}_${col}_idx`;
  if (full.length <= 63) return full;
  const h = createHash('sha1').update(full).digest('hex').slice(0, 6);
  return `${table.slice(0, 40)}_${col.slice(0, 8)}_${h}_idx`;
}
const indexSql = [];

function toModelName(recordKey) {
  return 'Sub_' + recordKey.replace(/-/g, '_');
}

function toColName(fieldKey) {
  // Prisma column names must be valid identifiers. Field keys are already camelCase from the
  // engine configs, but some might start with a digit or clash with reserved words.
  let col = fieldKey;
  if (/^\d/.test(col)) col = 'f_' + col;
  // Avoid Prisma reserved words
  if (['id', 'status', 'source', 'createdAt', 'updatedAt', 'submittedAt', 'rawJson', 'inSpec'].includes(col)) {
    col = 'val_' + col;
  }
  return col;
}

const lines = [];
lines.push('');
lines.push('// ============================================================================');
lines.push('// AUTO-GENERATED per-record submission tables.');
lines.push('// Generated by scripts/generate-submission-schema.mjs — do not edit by hand.');
lines.push('// ============================================================================');
lines.push('');

for (const def of definitions) {
  const model = toModelName(def.recordKey);
  const tableName = model.toLowerCase();

  // Separate roster fields from top-level fields; job-level copies are not stored at all.
  const skip = jobSnapshotKeys(def);
  const jobKey = jobFieldKey(def);
  const topFields = [];
  const rosterFields = [];
  for (const f of def.fields || []) {
    if (skip.has(f.key)) continue;
    const sec = def.sections && def.sections[f.sectionIndex];
    if (sec && sec.kind === 'roster') {
      rosterFields.push(f);
    } else {
      topFields.push(f);
    }
  }

  const hasRoster = rosterFields.length > 0;

  // ---- Parent model ----
  lines.push(`model ${model} {`);
  lines.push('  id          String    @id');
  lines.push('  status      String?');
  lines.push('  source      String?');
  lines.push('  submittedAt DateTime?');
  lines.push('  createdAt   DateTime  @default(now())');
  lines.push('  updatedAt   DateTime  @updatedAt');
  lines.push('  rawJson     String?');
  lines.push('  inSpec      Boolean?');
  lines.push('');

  const seenCols = new Set(['id', 'status', 'source', 'submittedAt', 'createdAt', 'updatedAt', 'rawJson', 'inSpec']);
  const indexCols = [];
  for (const f of topFields) {
    const col = f.key === jobKey ? JOB_COL : toColName(f.key);
    if (seenCols.has(col)) continue; // dedup
    seenCols.add(col);
    lines.push(`  ${col.padEnd(24)} ${prismaTypeFor(f, def)}`);
    if (f.linkField) indexCols.push(col);
  }

  if (hasRoster) {
    lines.push('');
    lines.push(`  rows ${model}_Row[]`);
  }

  lines.push('');
  for (const col of indexCols) {
    const name = indexName(tableName, col);
    lines.push(`  @@index([${col}], map: "${name}")`);
    indexSql.push(`CREATE INDEX "${name}" ON "${tableName}"("${col}");`);
  }
  lines.push(`  @@map("${tableName}")`);
  lines.push('}');
  lines.push('');

  // ---- Child (roster) model ----
  if (hasRoster) {
    const childModel = `${model}_Row`;
    const childTable = `${tableName}_row`;

    lines.push(`model ${childModel} {`);
    lines.push('  id       Int     @id @default(autoincrement())');
    lines.push(`  parentId String`);
    lines.push(`  parent   ${model} @relation(fields: [parentId], references: [id], onDelete: Cascade)`);
    lines.push('  position Int     @default(0)');
    lines.push('');

    const childSeen = new Set(['id', 'parentId', 'position']);
    for (const f of rosterFields) {
      const col = toColName(f.key);
      if (childSeen.has(col)) continue;
      childSeen.add(col);
      lines.push(`  ${col.padEnd(24)} ${prismaTypeFor(f, def)}`);
    }

    lines.push('');
    lines.push(`  @@index([parentId])`);
    lines.push(`  @@map("${childTable}")`);
    lines.push('}');
    lines.push('');
  }
}

const outPath = resolve(root, 'prisma/submission-models.prisma');
writeFileSync(outPath, lines.join('\n'), 'utf8');

console.log(`Generated ${definitions.length} submission models → ${outPath}`);
console.log(`Append to prisma/schema.prisma, then run: npx prisma migrate dev --name submission_tables`);

// `--index-sql` prints the CREATE INDEX statements for the link-field indexes above (for a migration).
if (process.argv.includes('--index-sql')) console.log(indexSql.join(String.fromCharCode(10)));
