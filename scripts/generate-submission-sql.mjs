#!/usr/bin/env node
// Generates the raw CREATE TABLE SQL for the per-record submission tables, matching the
// Prisma models in prisma/submission-models.prisma. Output goes to stdout or a migration file.
import { readFileSync, writeFileSync, mkdirSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, '..');
const { definitions } = JSON.parse(readFileSync(resolve(root, 'data/record-definitions.json'), 'utf8'));

function toTable(recordKey) {
  return 'sub_' + recordKey.replace(/-/g, '_');
}

function toCol(fieldKey) {
  let col = fieldKey;
  if (/^\d/.test(col)) col = 'f_' + col;
  if (['id', 'status', 'source', 'createdAt', 'updatedAt', 'submittedAt', 'rawJson', 'inSpec'].includes(col)) {
    col = 'val_' + col;
  }
  return `"${col}"`;
}

const lines = ['-- Per-record submission tables (Layer 2)', '-- Generated by scripts/generate-submission-sql.mjs', ''];

for (const def of definitions) {
  const table = toTable(def.recordKey);
  const topFields = [];
  const rosterFields = [];
  for (const f of def.fields || []) {
    const sec = def.sections && def.sections[f.sectionIndex];
    if (sec && sec.kind === 'roster') rosterFields.push(f);
    else topFields.push(f);
  }

  // Parent table
  const cols = [
    '"id" TEXT NOT NULL',
    '"status" TEXT',
    '"source" TEXT',
    '"submittedAt" TIMESTAMP(3)',
    '"createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP',
    '"updatedAt" TIMESTAMP(3) NOT NULL',
    '"rawJson" TEXT',
    '"inSpec" BOOLEAN',
  ];
  const seenCols = new Set(['id', 'status', 'source', 'submittedAt', 'createdAt', 'updatedAt', 'rawJson', 'inSpec']);
  for (const f of topFields) {
    let col = f.key;
    if (/^\d/.test(col)) col = 'f_' + col;
    if (seenCols.has(col)) continue;
    seenCols.add(col);
    cols.push(`"${col}" TEXT`);
  }
  cols.push(`CONSTRAINT "${table}_pkey" PRIMARY KEY ("id")`);
  lines.push(`CREATE TABLE "${table}" (`);
  lines.push('    ' + cols.join(',\n    '));
  lines.push(');');
  lines.push('');

  // Child (roster) table
  if (rosterFields.length) {
    const childTable = table + '_row';
    const childCols = [
      '"id" SERIAL NOT NULL',
      '"parentId" TEXT NOT NULL',
      '"position" INTEGER NOT NULL DEFAULT 0',
    ];
    const childSeen = new Set(['id', 'parentId', 'position']);
    for (const f of rosterFields) {
      let col = f.key;
      if (/^\d/.test(col)) col = 'f_' + col;
      if (childSeen.has(col)) continue;
      childSeen.add(col);
      childCols.push(`"${col}" TEXT`);
    }
    childCols.push(`CONSTRAINT "${childTable}_pkey" PRIMARY KEY ("id")`);
    lines.push(`CREATE TABLE "${childTable}" (`);
    lines.push('    ' + childCols.join(',\n    '));
    lines.push(');');
    lines.push('');
    lines.push(`CREATE INDEX "${childTable}_parentId_idx" ON "${childTable}"("parentId");`);
    lines.push(`ALTER TABLE "${childTable}" ADD CONSTRAINT "${childTable}_parentId_fkey" FOREIGN KEY ("parentId") REFERENCES "${table}"("id") ON DELETE CASCADE ON UPDATE CASCADE;`);
    lines.push('');
  }
}

const migDir = resolve(root, 'prisma/migrations/20260910000000_submission_tables');
mkdirSync(migDir, { recursive: true });
const outPath = resolve(migDir, 'migration.sql');
writeFileSync(outPath, lines.join('\n'), 'utf8');
console.log(`Generated ${definitions.length} tables → ${outPath}`);
console.log(`Lines: ${lines.length}`);
